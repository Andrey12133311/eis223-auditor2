const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {parseHTML}=require('linkedom');
const source=fs.readFileSync(require('node:path').join(__dirname,'../scripts/v299_browser_collector.js'),'utf8');
const helpers=source.slice(source.indexOf('  function valueByLabel('),source.indexOf('  function documentPageCandidates('));
const price=source.slice(source.indexOf('  function priceFromDocument('),source.indexOf('  async function reportOfficialPrice('));
const api=vm.runInNewContext(helpers+price+';({priceFromDocument})');
const make=body=>parseHTML('<html><body>'+body+'</body></html>').document;
const reg='32616471929';
const header='<h1>Закупка № '+reg+'</h1>';
assert.equal(api.priceFromDocument(make(header+'<div class="price-block"><div class="price-block__title">Начальная (максимальная) цена договора</div><div class="price-block__value">41 081,60 Российский рубль</div></div>'),reg),'41 081,60 ₽');
assert.equal(api.priceFromDocument(make(header+'<span class="title">НМЦД: 41 081,60 руб.</span>'),reg),'41 081,60 руб.');
assert.equal(api.priceFromDocument(make(header+'<table><tr><td>Начальная (максимальная) цена договора (цена лота)</td><td>41 081,60 ₽</td></tr></table>'),reg),'41 081,60 ₽');
assert.equal(api.priceFromDocument(make(header+'<div class="price-block__title">НМЦД</div><div class="price-block__value">0,00 ₽</div>'),reg),'0,00 ₽');
assert.equal(api.priceFromDocument(make('<h1>Закупка № 32616471928</h1><span class="title">НМЦД: 999 ₽</span>'),reg),'');
assert.equal(api.priceFromDocument(make(header+'<span class="title">Цена победителя: 999 ₽</span>'),reg),'');
assert.equal(api.priceFromDocument(make(header+'<span class="title">НМЦД: 100-200 ₽</span>'),reg),'');
const recovery=fs.readFileSync(require('node:path').join(__dirname,'../scripts/v335_price_recovery.py'),'utf8');
const ui=recovery.split("PRICE_JS=r'''<script id=\"v335-price-format\">\n")[1].split('</script>')[0];
const window={};vm.runInNewContext(ui,{window});
assert.equal(window.eis223PriceText({price_num:null,price:'1 234,56 ₽'}),'1\u00a0234,56 ₽');
assert.equal(window.eis223PriceText({price_num:null,price:null}),'Не указана в полученных данных');
assert.equal(window.eis223PriceText({price_num:'',price:'—'}),'Не указана в полученных данных');
assert.equal(window.eis223PriceText({price_num:0}),'0,00 ₽');
assert.equal(window.eis223PriceText({price_num:41081.60}),'41\u00a0081,60 ₽');
assert.match(window.eis223PriceText({price_num:2000000,price_kind:'maximum_contract_value'}),/максимальная цена договора/);
console.log('V335 price DOM regression: 13 checks passed');
